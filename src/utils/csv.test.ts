import test from 'node:test';
import assert from 'node:assert';
import {
  parseCSV,
  parseAndValidateMembersCSV,
  normalizePhoneNumber,
  normalizeDate,
  normalizeStatus,
} from './csv';
import { Member } from '../types';

const mockExistingMembers: Member[] = [
  {
    id: 'MEM-0001',
    memberId: 'MEM-0001',
    nameBn: 'হাজী মোঃ আকবর আলী',
    phone: '01708-122233',
    address: 'মধ্য সরকারপাড়া',
    joiningDate: '2020-01-01',
    status: 'active',
    position: 'সভাপতি',
    emergencyContact: '01700-000000',
    notes: '',
  },
  {
    id: 'MEM-0002',
    memberId: 'MEM-0002',
    nameBn: 'মোঃ রফিকুল ইসলাম',
    phone: '01712-345678',
    address: 'সরকারপাড়া',
    joiningDate: '2020-01-01',
    status: 'active',
    position: 'সাধারণ সম্পাদক',
    emergencyContact: '',
    notes: '',
  },
];

test('parseCSV handles quotes, commas, and newlines', () => {
  const csv = `"Name","Phone","Address"\n"John, Jr.","01711-223344","House 1, Road 2"\n"Rahim","01811-223344","Village"`;
  const parsed = parseCSV(csv);
  assert.strictEqual(parsed.length, 3);
  assert.strictEqual(parsed[1][0], 'John, Jr.');
  assert.strictEqual(parsed[1][1], '01711-223344');
  assert.strictEqual(parsed[1][2], 'House 1, Road 2');
  assert.strictEqual(parsed[2][0], 'Rahim');
});

test('normalizePhoneNumber converts Bengali numerals and strips non-digits', () => {
  assert.strictEqual(normalizePhoneNumber('০১৭১২-৩৪৫৬৭৮'), '01712345678');
  assert.strictEqual(normalizePhoneNumber('+8801712345678'), '01712345678');
  assert.strictEqual(normalizePhoneNumber('01712 345 678'), '01712345678');
});

test('normalizeDate converts Bengali digits and formats', () => {
  assert.strictEqual(normalizeDate('০৫/০৫/২০২৬'), '2026-05-05');
  assert.strictEqual(normalizeDate('2026-05-05'), '2026-05-05');
  assert.strictEqual(normalizeDate('15-08-2025'), '2025-08-15');
});

test('normalizeStatus handles English and Bengali statuses', () => {
  assert.strictEqual(normalizeStatus('সক্রিয়'), 'active');
  assert.strictEqual(normalizeStatus('নিষ্ক্রিয়'), 'inactive');
  assert.strictEqual(normalizeStatus('Active'), 'active');
  assert.strictEqual(normalizeStatus('Inactive'), 'inactive');
  assert.strictEqual(normalizeStatus('সাময়িক বরখাস্ত'), 'suspended');
});

test('parseAndValidateMembersCSV catches duplicates and validates required fields', () => {
  const csvContent = `সদস্য নম্বর,পূর্ণ নাম,মোবাইল নম্বর,ঠিকানা,পদবী,স্থিতি
MEM-0001,নকল সদস্য,01900-112233,সরকারপাড়া,সদস্য,সক্রিয়
MEM-0003,,01900-223344,সরকারপাড়া,সদস্য,সক্রিয়
MEM-0004,সঠিক সদস্য,01900-334455,সরকারপাড়া,সদস্য,সক্রিয়
MEM-0005,ডুপ্লিকেট ফোন সদস্য,01900-334455,সরকারপাড়া,সদস্য,সক্রিয়
,স্বয়ংক্রিয় আইডি সদস্য,01900-445566,সরকারপাড়া,সদস্য,সক্রিয়
`;

  const result = parseAndValidateMembersCSV(csvContent, mockExistingMembers);

  // 1. MEM-0001 already exists in mockExistingMembers -> Error
  assert.ok(result.errors.some((e) => e.field === 'memberId' && e.message.includes('ইতিমধ্যে সিস্টেমে বিদ্যমান')));

  // 2. Row with empty name -> Error
  assert.ok(result.errors.some((e) => e.field === 'nameBn' && e.message.includes('খালি থাকতে পারে না')));

  // 3. Row with duplicate phone in CSV -> Error
  assert.ok(result.errors.some((e) => e.field === 'phone' && e.message.includes('অভ্যন্তরীণ ডুপ্লিকেট')));

  // 4. Correct row with blank ID should have auto-generated ID (MEM-0003)
  const autoGenerated = result.validMembers.find((m) => m.member.nameBn === 'স্বয়ংক্রিয় আইডি সদস্য');
  assert.ok(autoGenerated);
  assert.ok(autoGenerated.member.memberId.startsWith('MEM-'));

  // 5. Total valid should be 2 (সঠিক সদস্য and স্বয়ংক্রিয় আইডি সদস্য)
  assert.strictEqual(result.validMembers.length, 2);
});

test('parseAndValidateMembersCSV identifies warning for phone already in system', () => {
  const csvContent = `সদস্য নম্বর,পূর্ণ নাম,মোবাইল নম্বর,ঠিকানা
MEM-0015,নতুন সদস্য,01712-345678,সরকারপাড়া
`;

  // 01712-345678 belongs to MEM-0002 in mockExistingMembers
  const result = parseAndValidateMembersCSV(csvContent, mockExistingMembers);
  assert.strictEqual(result.validMembers.length, 1);
  assert.strictEqual(result.validMembers[0].isDuplicatePhoneWarning, true);
  assert.ok(result.warnings.length > 0);
});
